#!/usr/bin/env node
/**
 * Generate the GL registration table from native-gles's own module.cpp.
 *
 * Hand-maintaining 250+ registrations would guarantee drift: a rename upstream would
 * surface as a missing function at runtime, in whichever game happened to call it.
 * Deriving the table from upstream's source means a bump either regenerates cleanly
 * or fails loudly at build time.
 *
 * Reads:  native-gles/src/module.cpp   (exports.Set("glFoo", ...<gl::_foo>...))
 *         native-gles/src/gl_bindings.h (return type per function: Value vs void)
 * Writes: src/gl_table.inc
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const GLES = resolve(ROOT, '..', 'native-gles', 'src');

const moduleSrc = readFileSync(join(GLES, 'module.cpp'), 'utf8');
const headerSrc = readFileSync(join(GLES, 'gl_bindings.h'), 'utf8');

/* Return type per binding: `Napi::Value _foo(...)` vs `void _foo(...)`. The thunk
   differs (one forwards a value, one returns undefined), so this must be exact. */
const returnsValue = new Map();
const declRe = /(Napi::Value|void)\s+(_[A-Za-z0-9_]+)\s*\(const\s+Napi::CallbackInfo/g;
for (let m; (m = declRe.exec(headerSrc)); ) {
  returnsValue.set(m[2], m[1] === 'Napi::Value');
}

/* Registrations: exports.Set("glFoo", Napi::Function::New<gl::_foo>(env)); */
const regRe = /exports\.Set\(\s*"([A-Za-z0-9_]+)"\s*,\s*Napi::Function::New<\s*gl::(_[A-Za-z0-9_]+)\s*>/g;
const rows = [];
const seen = new Set();
for (let m; (m = regRe.exec(moduleSrc)); ) {
  const [, jsName, cName] = m;
  if (seen.has(jsName)) continue;
  seen.add(jsName);
  if (!returnsValue.has(cName)) {
    console.error(`! ${jsName} -> gl::${cName} registered but not declared in gl_bindings.h`);
    continue;
  }
  rows.push({ jsName, cName, value: returnsValue.get(cName) });
}

if (!rows.length) {
  console.error('FATAL: no registrations parsed — upstream layout changed, fix this script');
  process.exit(1);
}

const out = [
  '/* GENERATED by scripts/gen-gl-table.mjs — do not edit.',
  ' * Source of truth: native-gles/src/module.cpp + gl_bindings.h',
  ` * ${rows.length} entry points.`,
  ' */',
  ...rows.map((r) => (r.value ? `GLFN("${r.jsName}", ${r.cName});`
                              : `GLFN_V("${r.jsName}", ${r.cName});`)),
  '',
].join('\n');

writeFileSync(join(ROOT, 'src', 'gl_table.inc'), out);
console.log(`generated src/gl_table.inc: ${rows.length} entry points ` +
            `(${rows.filter((r) => r.value).length} value, ${rows.filter((r) => !r.value).length} void)`);
